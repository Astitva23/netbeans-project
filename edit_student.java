    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
            int rollNo = Integer.parseInt(txtRollNo.getText().trim());
            String name = txtName.getText().trim();
            int studentClass = Integer.parseInt(txtClass.getText().trim());
            String section = cmbSection.getSelectedItem().toString();
            String gender = cmbGender.getSelectedItem().toString();
            String dob = txtDob.getText().trim();
            String phone = txtPhone.getText().trim();

            if (name.isEmpty() || dob.isEmpty() || phone.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
                return;
            }

            boolean updated = student_mgmt.updateStudent(
                    rollNo, name, studentClass, section, gender, dob, phone);

            if (updated) {
                javax.swing.JOptionPane.showMessageDialog(this, "Student Updated Successfully!");
                dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No student found with this Roll No.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Roll No and Class must be valid numbers.");
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error:\n" + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

