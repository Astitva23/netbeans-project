    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

  try {
        int rollNo = Integer.parseInt(jTextField1.getText().trim());

        boolean found = false;

        for (int i = 0; i < studentModel.getRowCount(); i++) {
            int tableRollNo = Integer.parseInt(
                    studentModel.getValueAt(i, 0).toString()
            );

            if (tableRollNo == rollNo) {
                tblStudents.setRowSelectionInterval(i, i);
                tblStudents.scrollRectToVisible(
                        tblStudents.getCellRect(i, 0, true)
                );

                found = true;
                break;
            }
        }

        if (!found) {
            JOptionPane.showMessageDialog(
                    this,
                    "Student not found!"
            );
        }

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Enter a valid roll number!"
        );
    }



        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

    try {
        int rollNo = Integer.parseInt(jTextField1.getText().trim());

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Delete student with Roll No. " + rollNo + "?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        boolean deleted = student_mgmt.deleteStudent(rollNo);

        if (deleted) {
            JOptionPane.showMessageDialog(
                    this,
                    "Student deleted successfully!"
            );

            studentModel.setRowCount(0);
            loadStudentRecords();
            jTextField1.setText("");

        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Student not found!"
            );
        }

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Enter a valid roll number!"
        );
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Database error: " + ex.getMessage()
        );
    }



        // TODO add your handling code here:
    }//GEN-LAST:event_jButton3ActionPerformed

